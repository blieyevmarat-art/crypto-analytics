-- ===============================================================================================================
-- HAVING - фильтрация после агрегации
-- ===============================================================================================================
-- ---------------------------------------------------------------------------------------------------------------
-- 1. Найти месяцы, в которых средняя цена BTC была выше 90,000 USDT
-- ---------------------------------------------------------------------------------------------------------------
select
	date_trunc('month', open_time) as month,
	round(cast(avg(close) as numeric), 2) as avg_price,
	count(*) as days
from crypto_prices
where symbol = 'BTCUSDT'
group by month
having avg(close) > 90000
order by month;

-- ===============================================================================================================
-- EXISTS и IN - подзапросы
-- ===============================================================================================================
-- ---------------------------------------------------------------------------------------------------------------
-- 1. Найти символы, у которых есть хотя бы один день с ценой выше 120,000 USDT.
-- ---------------------------------------------------------------------------------------------------------------
select *
from symbols
where symbol in (
	select distinct symbol
	from crypto_prices
	where close > 120000
);

-- ---------------------------------------------------------------------------------------------------------------
-- 2. Другой способ EXISTS
-- ---------------------------------------------------------------------------------------------------------------
select *
from symbols s
where exists (
	select 1
	from crypto_prices p
	where p.symbol = s.symbol and p.close > 12000
);

-- ===============================================================================================================
-- FULL OUTER JOIN - полное соединение
-- ===============================================================================================================
-- ---------------------------------------------------------------------------------------------------------------
-- Показать все символы из symbols и все данные из crypto_prices, даже если нет совпадений с обеих сторон
-- ---------------------------------------------------------------------------------------------------------------
select
	s.symbol as symbol_in_symbols,
	s.name,
	p.symbol as symbol_in_prices,
	p.open_time,
	p.close
from symbols s
full outer join crypto_prices p on s.symbol = p.symbol
order by s.symbol, p.open_time
limit 15;