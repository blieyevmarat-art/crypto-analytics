-- ---------------------------------------------------------------------------------------------------------------
-- 6. CASE WHEN - условная логика
-- Разделить дни на бычьи и медвежьи
-- ---------------------------------------------------------------------------------------------------------------
select
	open_time,
	close,
	lag(close) over (partition by symbol order by open_time) as prev_close,
	case
		when close > lag(close) over (partition by symbol order by open_time) then 'bullish'
		when close < lag(close) over (partition by symbol order by open_time) then 'bearish'
		else 'flat'
	end as day_type
from crypto_prices
where symbol = 'BTCUSDT'
order by open_time
limit 15;

-- ---------------------------------------------------------------------------------------------------------------
-- 7. Partition by - оконные функции по группам
-- Для каждого символа посчитать среднюю цену и отклонение от нее
-- ---------------------------------------------------------------------------------------------------------------
select
	symbol,
	open_time,
	close,
	round(cast(avg(close) over (partition by symbol) as numeric), 2) as avg_price_symbol,
	round(cast(close - avg(close) over (partition by symbol) as numeric), 2) as diff_from_avg
from crypto_prices
order by symbol, open_time
limit 20;

-- ---------------------------------------------------------------------------------------------------------------
-- 8. ROW_NUMBER с PARTITION BY
-- Для каждого символа найти топ-3 самых дорогих дня.
-- ---------------------------------------------------------------------------------------------------------------
with ranked as (
	select
		symbol,
		open_time,
		close,
		row_number() over (partition by symbol order by close desc) as rn
	from crypto_prices
)
select symbol, open_time, close, rn
from ranked
where rn <= 3
order by symbol, rn;

-- ---------------------------------------------------------------------------------------------------------------
-- 9. COALESCE - работа с NULL в prev_close на 'N/A' или на саму цену.
-- ---------------------------------------------------------------------------------------------------------------
select
	open_time,
	close,
	coalesce(lag(close) over (order by open_time), close) as prev_close_or_current,
	coalesce(
		round(cast((close - lag(close) over (order by open_time)) / lag(close) over (order by
		open_time) * 100 as numeric), 2),
		0
	) as return_pct
from crypto_prices
where symbol = 'BTCUSDT'
order by open_time
limit 10;

